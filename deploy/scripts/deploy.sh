#!/usr/bin/env bash
# SPDX-License-Identifier: AGPL-3.0-only
# Zero-downtime blue/green deploy of the API.
#
#   scripts/deploy.sh ghcr.io/skillpouch/api@sha256:…
#
# 1. pull  2. migrate (expand-only; failure stops here, live color untouched)
# 3. start idle color  4. wait for /readyz  5. canary-check its error rate
# 6. switch Caddy (graceful reload)  7. drain old color (SSE reconnect frames)
# 8. restart worker  9. smoke test — any failure rolls back automatically.
set -euo pipefail
cd "$(dirname "$0")/.."

IMAGE="${1:?usage: deploy.sh <api image>}"
COMPOSE=(docker compose --env-file env/stack.env)
STATE=caddy/.live-color
LIVE="$(cat "$STATE" 2>/dev/null || echo blue)"
IDLE=$([ "$LIVE" = blue ] && echo green || echo blue)
COLOR_VAR="API_IMAGE_${IDLE^^}"

log() { printf '[deploy] %s\n' "$*"; }
write_upstream() {
	cat > caddy/upstreams.caddy <<CADDY
# Generated by scripts/deploy.sh — the live API color.
reverse_proxy api-$1:8080 {
	lb_policy least_conn
	lb_try_duration 5s
	health_uri /readyz
	health_interval 2s
	flush_interval -1
}
CADDY
	"${COMPOSE[@]}" exec -T caddy caddy reload --config /etc/caddy/Caddyfile
}
rollback() {
	log "rolling back to $LIVE"
	write_upstream "$LIVE" || true
	"${COMPOSE[@]}" stop "api-$IDLE" || true
	exit 1
}

log "live=$LIVE idle=$IDLE image=$IMAGE"
export "$COLOR_VAR=$IMAGE" API_IMAGE="$IMAGE"
# Images built on the host (the Raspberry Pi builds its own) are not pulled.
docker image inspect "$IMAGE" >/dev/null 2>&1 || "${COMPOSE[@]}" pull "api-$IDLE"

log "migrating"
"${COMPOSE[@]}" run --rm migrate

log "starting api-$IDLE"
"${COMPOSE[@]}" up -d --no-deps "api-$IDLE"
for _ in $(seq 1 60); do
	if "${COMPOSE[@]}" exec -T "api-$IDLE" wget -qO- http://127.0.0.1:8080/readyz >/dev/null 2>&1; then READY=1; break; fi
	sleep 1
done
[ "${READY:-0}" = 1 ] || { log "api-$IDLE never became ready"; rollback; }

log "canary: checking api-$IDLE metrics for 30 s"
sleep 30
ERRORS=$("${COMPOSE[@]}" exec -T "api-$IDLE" wget -qO- http://127.0.0.1:9464/metrics \
	| awk '/skillpouch_http_request_duration_seconds_count/ && /status="5xx"/ {s+=$NF} END {print s+0}')
[ "${ERRORS%.*}" -le 5 ] || { log "canary saw $ERRORS 5xx responses"; rollback; }

log "switching traffic to api-$IDLE"
write_upstream "$IDLE"
echo "$IDLE" > "$STATE"

log "draining api-$LIVE (SSE clients get reconnect frames)"
"${COMPOSE[@]}" stop -t 30 "api-$LIVE"

log "restarting worker"
"${COMPOSE[@]}" up -d --no-deps worker

log "smoke test"
curl -fsS "${SMOKE_URL:-https://${PUBLIC_HOST:-app.skillpouch.net}/readyz}" >/dev/null || { LIVE_BACK=$LIVE; LIVE=$IDLE; IDLE=$LIVE_BACK; rollback; }
log "done: live=$IDLE"
