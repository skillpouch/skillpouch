/**
 * Writes a small account built with this package to `<target>` as JSON: a
 * roster with a CLI member, its welcome and key envelopes, and pouches that
 * were renamed and re-keyed. The CLI's tests open it to prove the Rust code
 * reads what the web writes.
 *
 *   pnpm --filter @skillpouch/crypto exec tsx scripts/cli-fixture.ts <target>
 */
import { p256 } from '@noble/curves/nist.js';
import { blake3 } from '@noble/hashes/blake3.js';
import type { KeyEnvelopeInput, RosterStatementInput } from '@skillpouch/contracts';
import { writeFileSync } from 'node:fs';
import {
	b64,
	buildAddMember,
	buildAuthorizeCli,
	buildCreatePouch,
	buildGenesis,
	buildRemoveMember,
	buildRenamePouch,
	generateMemberKeyPair,
	memberEntry,
	randomBytes,
	type PublicJwk,
} from '../src';

const target = process.argv[2];
if (!target) throw new Error('usage: cli-fixture.ts <target.json>');

const id = () => crypto.randomUUID();

function scalarKey(): { scalar: string; jwk: PublicJwk } {
	const scalar = p256.utils.randomSecretKey();
	const point = p256.getPublicKey(scalar, false);
	return {
		scalar: b64(scalar),
		jwk: {
			kty: 'EC',
			crv: 'P-256',
			x: b64(point.subarray(1, 33)),
			y: b64(point.subarray(33, 65)),
		},
	};
}

const accountId = id();
const [work, personal] = [id(), id()];
const statements: RosterStatementInput[] = [];
const envelopes: KeyEnvelopeInput[] = [];

const genesis = await buildGenesis({
	accountId,
	browserMemberId: id(),
	browserKeys: await generateMemberKeyPair(true),
	passwordSecret: randomBytes(64),
	passwordMemberId: id(),
	recoveryEntropy: randomBytes(32),
	recoveryMemberId: id(),
	pouchId: work,
	pouch: { name: 'Work', description: '' },
});
const keyring = genesis.keyring;
statements.push(...genesis.request.statements);

// A second browser that is removed later, which moves every pouch to generation 2.
const laptop = await generateMemberKeyPair(true);
const laptopId = id();
const added = await buildAddMember(keyring, memberEntry(laptopId, 'browser', laptop));
statements.push(added.statement.input);

const sign = scalarKey();
const enc = scalarKey();
const memberId = id();
const cli = await buildAuthorizeCli(
	keyring,
	{ requestId: id(), signPub: sign.jwk, encPub: enc.jwk, keyStorage: 'file' },
	memberId,
);
statements.push(cli.statement);
envelopes.push(...cli.key_envelopes);

const created = await buildCreatePouch(keyring, personal, {
	name: 'Personal ✨',
	description: 'side projects',
});
statements.push(created.statement);
envelopes.push(...created.key_envelopes);

const removed = await buildRemoveMember(keyring, laptopId);
statements.push(...removed.statements);
envelopes.push(...removed.key_envelopes);

const renamed = await buildRenamePouch(keyring, work, { name: 'Work stuff', description: '' });
statements.push(renamed.statement);

const fixture = {
	about: 'Generated by skillpouch/packages/crypto/scripts/cli-fixture.ts',
	account_id: accountId,
	member_id: memberId,
	sign_key: sign.scalar,
	enc_key: enc.scalar,
	welcome: cli.welcome,
	roster: statements.map((statement, seq) => ({
		seq,
		statement: statement.statement,
		statement_hash: b64(blake3(Buffer.from(statement.statement, 'base64url'))),
		signature: statement.signature,
	})),
	key_envelopes: envelopes.filter((envelope) => envelope.member_id === memberId),
	names: { [work]: 'Work stuff', [personal]: 'Personal ✨' },
};
writeFileSync(target, `${JSON.stringify(fixture, null, '\t')}\n`);
console.log(`wrote ${target}`);
