/** A Markdown table cell: no pipes or line breaks. */
export function cell(text) {
	return String(text).replaceAll('|', '\\|').replaceAll('\n', ' ');
}

function frontmatter(fields) {
	const lines = Object.entries(fields).map(([key, value]) => `${key}: ${JSON.stringify(value)}`);
	return `---\n${lines.join('\n')}\n---\n`;
}

const NOTICE = '<!-- Generated by scripts/gen-errors.mjs from packages/contracts. Do not edit. -->';

export function renderIndex(errors) {
	const rows = Object.entries(errors).map(
		([code, def]) =>
			`| [\`${code}\`](/errors/${code}/) | ${def.status} | ${def.retryable ? 'yes' : 'no'} | ${cell(def.message)} |`,
	);
	return [
		frontmatter({
			title: 'Error codes',
			description: 'Every error code the SkillPouch API answers with, and what it means.',
		}),
		NOTICE,
		'',
		'Every API error carries a stable `code`, the HTTP status, whether retrying the',
		'same request can succeed, and a link to its page here. Clients branch on the',
		'code; the message is a default text that may change.',
		'',
		'```json',
		'{ "ok": false, "error": { "code": "quota_exceeded", "message": "Storage quota exceeded." } }',
		'```',
		'',
		'| Code | HTTP | Retryable | Meaning |',
		'| ---- | ---- | --------- | ------- |',
		...rows,
		'',
	].join('\n');
}

export function renderErrorPage(code, def) {
	const hint = HINTS[code];
	const lines = [
		frontmatter({ title: code, description: def.message }),
		NOTICE,
		'',
		`> ${def.message}`,
		'',
		'| HTTP status | Retryable |',
		'| ----------- | --------- |',
		`| ${def.status} | ${def.retryable ? 'yes: the same request can succeed later' : 'no'} |`,
		'',
	];
	if (def.deprecated) {
		lines.push(':::caution', 'This code is deprecated: the API no longer sends it.', ':::', '');
	}
	if (hint) {
		lines.push('## What to do', '', hint, '');
	}
	lines.push('See all [error codes](/errors/).', '');
	return lines.join('\n');
}

/** `{ 'index.md': …, '<code>.md': … }` for the registry. */
export function renderAll(errors) {
	const files = { 'index.md': renderIndex(errors) };
	for (const [code, def] of Object.entries(errors)) {
		files[`${code}.md`] = renderErrorPage(code, def);
	}
	return files;
}

function main() {
	const errors = JSON.parse(readFileSync(REGISTRY, 'utf8'));
	rmSync(OUT_DIR, { recursive: true, force: true });
	mkdirSync(OUT_DIR, { recursive: true });
	const files = renderAll(errors);
	for (const [name, content] of Object.entries(files)) {
		writeFileSync(join(OUT_DIR, name), content);
	}
	console.log(`gen-errors: ${Object.keys(files).length - 1} codes → src/content/docs/errors/`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
	main();
}
